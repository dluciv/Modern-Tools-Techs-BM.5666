def load_corpus(pattern: str = "markov*.txt", directory: Path | None = None) -> list[str]:
    """Читает текстовые файлы корпуса и добавляет их к встроенным фразам.

    Ищем относительно папки этого модуля, а не текущей рабочей директории:
    иначе запуск из другой папки тихо оставил бы модель без страшилок.
    """
    base = directory if directory is not None else Path(__file__).parent
    texts = list(BUILTIN_CORPUS)

    for path in sorted(base.glob(pattern)):
        text = path.read_text(encoding="utf-8").strip()
        if text:
            texts.append(text)

    return texts


def tokenize(text: str) -> list[str]:
    """Токенизация: слово вместе с прилипшей к нему пунктуацией.

    Раньше знаки препинания были отдельными токенами, и при order=4
    окно в четыре токена — это три слова и одна запятая. Из-за этого
    текст почти никогда не попадал в цепь. Теперь запятая входит
    в слово: "знаю." — один токен, и окно считает настоящие слова.
    """
    return re.findall(r"[^\w\s]*\w+[^\w\s]*", text.lower())


def ends_sentence(token: str) -> bool:
    """Заканчивает ли токен предложение (внутри есть точка, ! или ?)."""
    return bool(token) and token[-1] in ".!?"


# Знаки, которые снимаем перед стеммингом и при сравнении слов
PUNCTUATION = ".,!?;:—–-\"'()[]{}«»…"


def word_form(token: str) -> str:
    """Токен без пунктуации — для сравнения слов при поиске состояния.

    Цепь живёт на токенах вида "парк.", а вопрос приходит словами "парк".
    Если не снять пунктуацию, они не совпадут, и поиск не найдёт ничего.
    """
    return token.strip(PUNCTUATION)


# Окончания, которые почти всегда можно срезать.
# Порядок важен: сначала длинные, иначе "ирования" срежется как "иров".
# Здесь нет ни Porter, ни Snowball — это нарочно грубый список, чтобы
# его можно было прочитать целиком и понять, что именно он отрезает.
SUFFIXES: tuple[str, ...] = (
    # причастия и деепричастия
    "ившись", "ывшись", "ивши", "ывши", "ующ", "ающ",
    "ующий", "ующая", "ующие",
    # глаголы: сначала самые длинные хвосты, иначе "ованием" съест "ать"
    "ованием", "ированием", "ирование", "ование", "овать",
    "ует", "ает", "яет", "овав", "овал", "ить", "ыть", "ать", "ять",
    "еть", "ла", "ло", "ли", "ть", "ся", "сь",
    # прилагательные и сравнительные степени
    "ыми", "ими", "его", "ому", "ий", "ый", "ая", "яя", "ое", "ее",
    "ые", "ие", "ем", "им",
    # существительные
    "ами", "ями", "ах", "ях", "ов", "ев", "ей", "ой", "ам", "ям",
    # остальные частые хвосты
    "ую", "ю", "я", "а", "о", "е", "у", "ы", "и", "ь", "й",
)

# Короче этой длины не режем: иначе "год" превратится в пустую строку
# и короткие служебные слова начнут слипаться в одно
MIN_STEM_LENGTH = 4


def stem(word: str) -> str:
    """Грубый стеммер: срезает самое длинное подходящее окончание.

    Нужен, чтобы «тестирование», «теста» и «тесты» стали одним и тем же
    состоянием цепи. Настоящий алгоритм Портера здесь ни при чём — мы
    сознательно выбрали вариант, который читается за минуту.
    """
    for suffix in SUFFIXES:
        if word.endswith(suffix) and len(word) - len(suffix) >= MIN_STEM_LENGTH:
            return word[: -len(suffix)]
    return word


def stem_tokens(tokens: list[str]) -> list[str]:
    """Основы всех токенов — ровно то, чем ключуется цепь.

    Пунктуацию снимаем до стемминга, иначе "делать?" и "делать"
    оказались бы разными словами.
    """
    return [stem(word_form(token)) for token in tokens]


def detokenize(tokens: list[str]) -> str:
    """Собираем токены обратно в текст.

    Знаки препинации сидят внутри слов, поэтому просто соединяем
    всё пробелами: "привет," + "мир!" -> "Привет, мир!"
    """
    if not tokens:
        return ""

    result = " ".join(tokens)

    if result[0].isalpha():
        result = result[0].upper() + result[1:]

    return result
