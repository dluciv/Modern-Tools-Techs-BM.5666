HELP = "Пишите текстом. «выход» — закончить разговор."


def chat() -> None:
    """Простой диалог в терминале."""
    eliza = Eliza()

    print(GREETING)
    print(HELP)

    while True:
        try:
            line = input("Вы: ").strip()
        except (EOFError, KeyboardInterrupt):
            print()
            break

        if line.lower() in {"выход", "quit", "exit", "q"}:
            print("Элиза: До свидания!")
            break

        if not line:
            continue

        print(f"Элиза: {eliza.respond(line)}")


if __name__ == "__main__":
    chat()
