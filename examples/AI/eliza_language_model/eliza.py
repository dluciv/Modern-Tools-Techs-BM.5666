# Знаки препинания убираются из входа: правила ищут слова, а не знаки,
# иначе «мне?» не совпадёт с «мне».
PUNCTUATION = re.compile(r"[.,!?;:—–\-«»\"'()\[\]{}]")
WORD = re.compile(r"[^\W\d_]+")


def compile_table(table: dict[str, str]) -> list[tuple[re.Pattern[str], str]]:
    """Готовит замены, сначала самые длинные ключи.

    Порядок важен: иначе «не люблю» превратится в «не любите» раньше,
    чем сработает правило для «люблю».
    """
    return [
        (re.compile(rf"\b{re.escape(key)}\b"), value)
        for key, value in sorted(table.items(), key=lambda item: -len(item[0]))
    ]


REFLECTIONS = compile_table(DEIXIS)
CONJUGATIONS = compile_table(VERBS)


def words_of(text: str) -> list[str]:
    """Текст -> список слов в нижнем регистре, без знаков препинания."""
    return WORD.findall(PUNCTUATION.sub(" ", text.lower()))


def word_matches(word: str, keyword: str) -> bool:
    """Подходит ли слово под ключевое.

    Сравнение идёт по началу слова — так «код» находит «кодом»,
    «работа» находит «работает», «марков» находит «марковскую».
    Короткие служебные слова (см. EXACT_ONLY) сравниваются целиком,
    иначе «вы» совпадёт с «высокий», а «ок» — с «окно».
    """
    if word == keyword:
        return True
    if keyword in EXACT_ONLY:
        return False
    return len(keyword) >= MIN_PREFIX_LENGTH and word.startswith(keyword)


def reflect(words: list[str]) -> str:
    """Слова собеседника -> слова от его лица.

    Сначала спряжение («люблю» -> «любите»), потом отражения
    («мне» -> «вам»). Обратный порядок сломал бы глаголы.
    """
    # Хвост часто начинается вводным словом: без его удаления
    # получится «Вы полагаете, что что это правда».
    while words and words[0] in TAIL_FILLERS:
        words = words[1:]

    text = " ".join(words)
    for pattern, replacement in CONJUGATIONS:
        text = pattern.sub(replacement, text)
    for pattern, replacement in REFLECTIONS:
        text = pattern.sub(replacement, text)
    return text.strip()


def fill(template: str, tail: str) -> str:
    """Подставляет хвост фразы вместо «*» и приводит текст к виду."""
    if "*" not in template:
        return template.strip()

    if not tail:
        return ""

    text = template.replace("*", tail).strip()
    text = text[0].upper() + text[1:]
    if text[-1] not in ".!?":
        text += "."
    return text


def agent_reply_of(message: str) -> tuple[str, str]:
    """Проверяет, не служебный ли это запрос агента.

    Возвращает пару (слово, по которому узнали запрос, ответ), а если
    запрос обычный — ("", ""). Слово нужно журналу: он показывает, какая
    именно заготовка сработала.
    """
    lowered = message.lower()
    for key, response in AGENT_RESPONSES.items():
        if key in lowered:
            return key, response
    return "", ""


def truncate(reply: str, max_tokens: int) -> str:
    """Ограничивает ответ по числу слов — как max_tokens у настоящих моделей."""
    words = reply.split()
    if len(words) <= max_tokens:
        return reply
    return " ".join(words[:max_tokens]).rstrip(",;:") + "…"


